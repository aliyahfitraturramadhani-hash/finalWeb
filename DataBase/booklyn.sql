BEGIN;

-- Hapus ulang (urutan terbalik dari dependensi) agar script bisa dijalankan berulang saat development
DROP TABLE IF EXISTS reviews     CASCADE;
DROP TABLE IF EXISTS fines       CASCADE;
DROP TABLE IF EXISTS loan_items  CASCADE;
DROP TABLE IF EXISTS loans       CASCADE;
DROP TABLE IF EXISTS book_copies CASCADE;
DROP TABLE IF EXISTS books       CASCADE;
DROP TABLE IF EXISTS categories  CASCADE;
DROP TABLE IF EXISTS members     CASCADE;
DROP TABLE IF EXISTS users       CASCADE;


-- ---------------------------------------------------------------------
-- 1. users
-- ---------------------------------------------------------------------
CREATE TABLE users (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama             VARCHAR(100) NOT NULL,
  email            VARCHAR(150) NOT NULL UNIQUE,
  password_hash    TEXT         NOT NULL,
  no_hp            VARCHAR(20),
  nomor_identitas  VARCHAR(30),
  role             VARCHAR(20)  NOT NULL
                   CHECK (role IN ('admin', 'librarian', 'member')),
  status           VARCHAR(20)  NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('active', 'pending', 'rejected', 'suspended')),
  alasan_penolakan TEXT,
  created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
  -- alasan wajib jika rejected
  CONSTRAINT chk_users_alasan_penolakan
    CHECK (status <> 'rejected' OR alasan_penolakan IS NOT NULL)
);
CREATE UNIQUE INDEX uq_users_email_lower ON users (LOWER(email));
CREATE INDEX idx_users_role_status ON users (role, status);

-- ---------------------------------------------------------------------
-- 2. members
-- ---------------------------------------------------------------------
CREATE TABLE members (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         BIGINT      NOT NULL UNIQUE
                  REFERENCES users(id) ON DELETE CASCADE,
  nomor_anggota   VARCHAR(20) UNIQUE,          -- NULL sebelum Approved
  nomor_identitas VARCHAR(30) NOT NULL,        -- KTP / kartu pelajar
  alamat          TEXT,
  masa_berlaku    DATE,                        -- NULL sebelum Approved
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 3. categories
-- ---------------------------------------------------------------------
CREATE TABLE categories (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_kategori    VARCHAR(100) NOT NULL UNIQUE,
  kode_klasifikasi VARCHAR(20),
  deskripsi        TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_categories_nama_lower ON categories (LOWER(nama_kategori));

-- ---------------------------------------------------------------------
-- 4. books
-- ---------------------------------------------------------------------
CREATE TABLE books (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id     BIGINT        NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
  isbn            VARCHAR(20)   UNIQUE,
  judul           VARCHAR(200)  NOT NULL,
  penulis         VARCHAR(150)  NOT NULL,
  penerbit        VARCHAR(150),
  tahun_terbit    SMALLINT      CHECK (tahun_terbit BETWEEN 1000 AND 2100),
  deskripsi       TEXT          NOT NULL,
  sampul          TEXT,
  lokasi_rak      VARCHAR(50),
  harga_pengganti NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (harga_pengganti >= 0),
  deleted_at      TIMESTAMPTZ,                 -- soft delete
  created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_books_category   ON books (category_id);
CREATE INDEX idx_books_judul      ON books (LOWER(judul));
CREATE INDEX idx_books_penulis    ON books (LOWER(penulis));
CREATE INDEX idx_books_active     ON books (id) WHERE deleted_at IS NULL;

-- ---------------------------------------------------------------------
-- 5. book_copies
-- ---------------------------------------------------------------------
CREATE TABLE book_copies (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id         BIGINT      NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
  kode_eksemplar  VARCHAR(30) NOT NULL UNIQUE,
  kondisi         VARCHAR(20) NOT NULL DEFAULT 'baik'
                  CHECK (kondisi IN ('baik', 'rusak_ringan', 'rusak_berat')),
  status          VARCHAR(20) NOT NULL DEFAULT 'tersedia'
                  CHECK (status IN ('tersedia', 'ditahan', 'dipinjam', 'dalam_perbaikan', 'hilang')),
  tanggal_masuk   DATE        NOT NULL DEFAULT CURRENT_DATE,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_copies_book_status ON book_copies (book_id, status);

-- ---------------------------------------------------------------------
-- 6. loans
-- ---------------------------------------------------------------------
CREATE TABLE loans (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_pinjam          VARCHAR(30) NOT NULL UNIQUE,
  member_id            BIGINT      NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
  processed_by         BIGINT      REFERENCES users(id) ON DELETE SET NULL,
  status               VARCHAR(30) NOT NULL DEFAULT 'menunggu_pengambilan'
                       CHECK (status IN ('menunggu_pengambilan', 'dipinjam', 'dikembalikan', 'dibatalkan')),
  batas_ambil          TIMESTAMPTZ NOT NULL,
  tanggal_pinjam       TIMESTAMPTZ,
  jatuh_tempo          DATE,
  jumlah_perpanjangan  SMALLINT    NOT NULL DEFAULT 0
                       CHECK (jumlah_perpanjangan BETWEEN 0 AND 1),
  catatan              TEXT,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- status dipinjam wajib punya tanggal pinjam & jatuh tempo
  CONSTRAINT chk_loans_dipinjam
    CHECK (status NOT IN ('dipinjam', 'dikembalikan')
           OR (tanggal_pinjam IS NOT NULL AND jatuh_tempo IS NOT NULL))
);
CREATE INDEX idx_loans_member_status ON loans (member_id, status);
CREATE INDEX idx_loans_status_jatuh_tempo ON loans (status, jatuh_tempo);

-- ---------------------------------------------------------------------
-- 7. loan_items
-- ---------------------------------------------------------------------
CREATE TABLE loan_items (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id          BIGINT      NOT NULL REFERENCES loans(id) ON DELETE CASCADE,
  copy_id          BIGINT      NOT NULL REFERENCES book_copies(id) ON DELETE RESTRICT,
  tanggal_kembali  TIMESTAMPTZ,
  kondisi_kembali  VARCHAR(20) CHECK (kondisi_kembali IN ('baik', 'rusak', 'hilang')),
  CONSTRAINT uq_loan_items_loan_copy UNIQUE (loan_id, copy_id),
  -- tanggal_kembali dan kondisi_kembali harus terisi bersamaan
  CONSTRAINT chk_loan_items_kembali
    CHECK ((tanggal_kembali IS NULL) = (kondisi_kembali IS NULL))
);
CREATE INDEX idx_loan_items_copy ON loan_items (copy_id);

-- ---------------------------------------------------------------------
-- 8. fines
-- ---------------------------------------------------------------------
CREATE TABLE fines (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_item_id        BIGINT        NOT NULL REFERENCES loan_items(id) ON DELETE RESTRICT,
  jenis               VARCHAR(20)   NOT NULL CHECK (jenis IN ('terlambat', 'rusak', 'hilang')),
  hari_terlambat      INTEGER       NOT NULL DEFAULT 0 CHECK (hari_terlambat >= 0),
  tarif_per_hari      NUMERIC(12,2),             -- snapshot; NULL jika bukan terlambat
  jumlah_denda        NUMERIC(12,2) NOT NULL CHECK (jumlah_denda >= 0),
  status              VARCHAR(20)   NOT NULL DEFAULT 'belum_dibayar'
                      CHECK (status IN ('belum_dibayar', 'lunas', 'dihapuskan')),
  alasan_penghapusan  TEXT,
  processed_by        BIGINT        REFERENCES users(id) ON DELETE SET NULL,
  dibayar_at          TIMESTAMPTZ,
  created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
  CONSTRAINT uq_fines_item_jenis UNIQUE (loan_item_id, jenis),
  CONSTRAINT chk_fines_alasan
    CHECK (status <> 'dihapuskan' OR alasan_penghapusan IS NOT NULL)
);
CREATE INDEX idx_fines_status ON fines (status);

-- ---------------------------------------------------------------------
-- 9. reviews
-- ---------------------------------------------------------------------
CREATE TABLE reviews (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_item_id  BIGINT      NOT NULL UNIQUE REFERENCES loan_items(id) ON DELETE CASCADE,
  book_id       BIGINT      NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
  member_id     BIGINT      NOT NULL REFERENCES members(id) ON DELETE CASCADE,
  rating        SMALLINT    NOT NULL CHECK (rating BETWEEN 1 AND 5),
  komentar      TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_reviews_book ON reviews (book_id);

