BEGIN;

-- 1. ANNOUNCEMENTS
CREATE TABLE IF NOT EXISTS announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judul VARCHAR(200) NOT NULL,
    isi TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'published', 'archived')),
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_announcements_status
ON announcements(status);


-- 2. EXTENSION REQUESTS
CREATE TABLE IF NOT EXISTS extension_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    loan_id BIGINT NOT NULL
        REFERENCES loans(id) ON DELETE CASCADE,

    member_id BIGINT NOT NULL
        REFERENCES members(id) ON DELETE CASCADE,

    alasan TEXT,

    tanggal_jatuh_tempo_lama DATE NOT NULL,
    tanggal_jatuh_tempo_baru DATE NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),

    processed_by BIGINT
        REFERENCES users(id) ON DELETE SET NULL,

    catatan_petugas TEXT,

    requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    processed_at TIMESTAMPTZ,

    CHECK (tanggal_jatuh_tempo_baru > tanggal_jatuh_tempo_lama)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_extension_pending
ON extension_requests(loan_id)
WHERE status = 'pending';

COMMIT;